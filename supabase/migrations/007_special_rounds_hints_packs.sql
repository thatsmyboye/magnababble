--   1. Special rounds: a per-round modifier (double / speed / chaos)
--   2. Soft slot hints: the word type each blank expects
--   3. Grammar fixes for frames that expected a past-tense verb
--   4. Family-friendly flags on prompts and tiles
--   5. The Spooky pack: a themed tile set with its own prompts
-- Safe to re-run.
-- ============================================================

-- 1. Special rounds -----------------------------------------------------
ALTER TABLE rounds ADD COLUMN IF NOT EXISTS modifier TEXT;
ALTER TABLE rounds DROP CONSTRAINT IF EXISTS rounds_modifier_check;
ALTER TABLE rounds
  ADD CONSTRAINT rounds_modifier_check CHECK (modifier IS NULL OR modifier IN ('double', 'speed', 'chaos'));

-- 2 & 4. New columns ------------------------------------------------------
-- slot_hints[i] is the tile category blank i expects (noun, verb,
-- adjective, adverb, filler). Hints guide dealing and show on the blank;
-- players may still place any tile.
ALTER TABLE prompts ADD COLUMN IF NOT EXISTS slot_hints TEXT[];
ALTER TABLE prompts ADD COLUMN IF NOT EXISTS family_friendly BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE tiles   ADD COLUMN IF NOT EXISTS family_friendly BOOLEAN NOT NULL DEFAULT true;

